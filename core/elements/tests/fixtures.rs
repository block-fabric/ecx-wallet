//! The fixture PSETs the e2e suite (Seam 1) sends, generated from the same builders as Seam 2 and
//! committed at `e2e/fixtures/elements-psets.json`. This test fails if the committed file drifts;
//! `UPDATE_FIXTURES=1 cargo test -p ecx-elements --test fixtures` rewrites it.
mod common;

use common::*;
use lwk_common::Signer;
use serde_json::json;

const PATH: &str = concat!(env!("CARGO_MANIFEST_DIR"), "/../../e2e/fixtures/elements-psets.json");

#[test]
fn the_committed_e2e_fixtures_are_up_to_date() {
    let blind = transfer_with_unknown_fields();
    // The expected answer, signed by LWK's SwSigner directly (input 0 is the only one it can sign).
    let mut signed = blind.clone();
    lwk_signer::SwSigner::new(STARTER, false).unwrap().sign(&mut signed).unwrap();

    let fixtures = json!({
        "_comment": "Generated by core/elements/tests/fixtures.rs; wallet = Slot 24 Starter of abandon…about.",
        "blind": { "payload": b64(&blind), "signed": b64(&signed) },
        "wrongGenesis": { "payload": b64(&{
            let mut p = transfer();
            set_genesis(&mut p, "1466275836220db2944ca059a3a10ef6fd2ea684b0688d2c379296888a206003");
            p
        }) },
        "confidentialInput": { "payload": b64(&with_confidential_input()) },
        "confidentialOutput": { "payload": b64(&with_confidential_output()) },
        "missingDerivation": { "payload": b64(&with_missing_derivation()) },
    });
    let text = serde_json::to_string_pretty(&fixtures).unwrap() + "\n";
    if std::env::var_os("UPDATE_FIXTURES").is_some() {
        std::fs::create_dir_all(std::path::Path::new(PATH).parent().unwrap()).unwrap();
        std::fs::write(PATH, &text).unwrap();
    }
    let committed = std::fs::read_to_string(PATH).unwrap_or_default();
    assert!(committed == text, "{PATH} is stale; rerun with UPDATE_FIXTURES=1");
}
